"""Guards that keep ground truth, identities, synthetic data and future information out of model inputs."""
import re

import pandas as pd

from ml.cert.schema import FORBIDDEN_FEATURE_COLUMNS, MODEL_INPUT_COLUMNS, SOURCE_CERT


class LeakageError(Exception):
    pass


_SUSPECT_NAME = re.compile(r"(label|scenario|insider|answer|incident|ground_?truth|malicious|user_?id|entity)", re.I)


def assert_no_leakage(feature_columns) -> None:
    """Raise if a feature list contains ground truth, answer-key fields, identity, split or provenance columns."""
    columns = list(feature_columns)
    forbidden = sorted(set(columns) & FORBIDDEN_FEATURE_COLUMNS)
    suspicious = sorted(c for c in columns if c not in forbidden and _SUSPECT_NAME.search(c))
    if forbidden or suspicious:
        raise LeakageError(f"Forbidden or suspicious feature column(s): {forbidden + suspicious}. Labels, answer-key fields, "
                           "identities, split assignment and provenance must not be model inputs.")


def model_input_view(events: pd.DataFrame) -> pd.DataFrame:
    """Event-level columns a detector may read. Labels, identity and provenance are not included."""
    missing = [c for c in MODEL_INPUT_COLUMNS if c not in events.columns]
    if missing:
        raise LeakageError(f"events lack expected input column(s) {missing}")
    view = events[list(MODEL_INPUT_COLUMNS)].copy()
    assert_no_leakage(view.columns)
    return view


def assert_cert_only(events: pd.DataFrame) -> None:
    """The held-out CERT test set must contain nothing generated by this project."""
    if "is_synthetic" in events and events["is_synthetic"].astype(bool).any():
        raise LeakageError("Synthetic events found in a CERT dataset-backed evaluation set")
    if "source" in events and (events["source"] != SOURCE_CERT).any():
        raise LeakageError(f"Events from sources other than {SOURCE_CERT} found in a CERT evaluation set: "
                           f"{sorted(set(events['source']) - {SOURCE_CERT})}")


def assert_disjoint_users(splits: pd.DataFrame) -> None:
    if splits["entity_id"].duplicated().any():
        raise LeakageError("A user appears in more than one split")


def history_before(events: pd.DataFrame, as_of, entity_id: str | None = None) -> pd.DataFrame:
    """Events strictly earlier than `as_of` (never the event being scored or anything after it)."""
    stamps = pd.to_datetime(events["timestamp_utc"])
    mask = stamps < pd.Timestamp(as_of)
    if entity_id is not None:
        mask &= events["entity_id"] == entity_id
    return events[mask]
